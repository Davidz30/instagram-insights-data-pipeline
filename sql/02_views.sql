CREATE OR ALTER VIEW dbo.vw_instagram_account_insights AS
SELECT INSTAGRAM_ID, DTA_INICIO, DTA_FIM, FOLLOWERS_COUNT,
       MEDIA_COUNT, REACH, PROFILE_VIEWS, ACCOUNTS_ENGAGED, DTA_CARGA
FROM dbo.f_instagram_insights_conta;
GO
CREATE OR ALTER VIEW dbo.vw_instagram_media_insights AS
SELECT MEDIA_ID, INSTAGRAM_ID, DTA_PUBLICACAO, MEDIA_TYPE,
       MEDIA_PRODUCT_TYPE, LIKE_COUNT, COMMENTS_COUNT,
       REACH, SAVED, SHARES, TOTAL_INTERACTIONS, DTA_CARGA
FROM dbo.f_instagram_midias;
GO
